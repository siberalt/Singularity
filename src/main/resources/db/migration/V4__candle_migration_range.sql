-- Чекпойнт миграции свечей: непрерывные временные диапазоны, уже успешно
-- перенесённые для инструмента. Хранятся в виде набора непересекающихся
-- и не соседствующих впритык интервалов (при добавлении соседние/пересекающиеся
-- диапазоны сливаются в один) - это делает чекпойнт независимым от того,
-- какой был размер чанка и с какой точки началась миграция в конкретном запуске.
CREATE TABLE IF NOT EXISTS candle_migration_range (
    instrument_uid TEXT NOT NULL,
    range_from INTEGER NOT NULL,  -- начало диапазона, epoch millis
    range_to INTEGER NOT NULL,    -- конец диапазона, epoch millis
    PRIMARY KEY (instrument_uid, range_from)
);
