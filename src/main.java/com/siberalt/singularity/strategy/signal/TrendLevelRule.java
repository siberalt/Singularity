package com.siberalt.singularity.strategy.signal;

import com.siberalt.singularity.strategy.market.MarketCoefficient;
import com.siberalt.singularity.strategy.market.MarketCondition;
import com.siberalt.singularity.strategy.market.PriceAbove;
import com.siberalt.singularity.strategy.market.SteadySide;
import com.siberalt.singularity.strategy.signal.condition.OfType;

import java.util.List;

/**
 * Правило «уровень плюс режим», собранное из готовых частей: трендовая ветка в {@link #trendBranch} и
 * переключатель между ветками по размеченному режиму в {@link #byRegime}.
 * <p>
 * Фабрика, а не класс с поведением: всё содержание здесь - композиция, и собрана она отдельно от стенда,
 * чтобы её можно было прочитать и проверить тестом, а не только прогнать.
 *
 * <h2>Вход на пересечении, а не на откате к средней</h2>
 * Это отличие от первоначальной задумки, и оно от измерения, а не от вкуса. В {@code docs/signals.md} на
 * 577 событиях по всем 33 бумагам: вход на кресте даёт <b>+182.9 ± 94</b> бп на двадцати днях, откат к
 * SMA(50) - <b>минус 58.6 ± 39</b>, откат к SMA(200) - минус 202. Добавление RSI или объёма к откату делает
 * хуже. Причина в самих числах: крест отмечает начало фазы, а откат случается внутри фазы многократно,
 * включая её вершину, и глубокий откат внутри «восходящей» фазы чаще оказывается не скидкой, а трендом,
 * который вот-вот сломается.
 * <p>
 * Откату место во флэтовой ветке: измерение делалось <i>внутри восходящих фаз</i> и про флэт не говорит
 * ничего, а возврату к средней место именно там.
 * <p>
 * «На пересечении» - это событие, поэтому {@link OnChangeSignalSource} поверх меры тренда: сама мера
 * отвечает состоянием и на каждом баре фазы говорит одно и то же.
 *
 * <h2>Выход: решительный пробой, а выше средней - только фиксация прибыли</h2>
 * Пока цена выше уровня, обычные выходы не пропускаются, а {@link SignalType#TAKE_PROFIT} проходит. Это
 * ровно то, что просили, но стоит знать его цену: в этой базе измерено, что цена одностороннего фильтра
 * пропорциональна длительности вето - RSI-вето держалось месяцами и стоило <b>51 пункт на 33 бумагах из
 * 33</b>, а мёртвая зона держалась дни и дала десяток на грани шума. «Цена выше средней» живёт месяцами, то
 * есть это вето самого дорогого вида, и мерить его надо отдельным рукавом, а не принимать на веру.
 * <p>
 * «Пробой под прямым углом» недостижим буквально: в {@link ChangeAngleSignalSource} угол нормирован средним
 * абсолютным приращением и по неравенству треугольника не выходит за ±45°, где предел означает «все бары в
 * одну сторону». Поэтому решительность выражается близостью к пределу.
 * <p>
 * Сама же решительность сюда не передаётся: она входит в <b>уровень</b> через
 * {@link com.siberalt.singularity.strategy.market.TolerantLevel}, и поэтому здесь остаётся одна проверка
 * вместо пары «под уровнем и круто». Что ещё важнее, у той пары была дырка - медленный дрейф, ушедший на
 * десять процентов вниз, не выходил никогда, потому что круто он так и не падал.
 * <p>
 * Оговорка про исполнимость, которую стоит помнить при чтении результатов: сигнал считается по закрытию
 * бара, а заявка доходит через бар, поэтому «выход на самом уровне» на резком ходу недостижим именно
 * тогда, когда он нужен - цена проходит уровень внутри бара. Один день опоздания в этой базе измерен в 27
 * пунктов. Исполнимая версия резкого выхода - заранее выставленный стоп на уровне, а не реакция на пробой;
 * здесь реализована реакция, и её запаздывание - часть измеряемого, а не дефект сборки.
 */
public final class TrendLevelRule {
    private TrendLevelRule() {
    }

    /**
     * Середина между объявленными сторонами режима. {@link SteadySide} отдаёт ровно {@code -1}, {@code 0}
     * или {@code 1}, так что попасть на границу нечем и её положение условно; а если режимом окажется
     * непрерывная мера вроде голого {@link com.siberalt.singularity.strategy.market.TrendAngle}, то это
     * честный порог в половину предела, то есть 22.5°.
     */
    private static final double MIDDLE = 0.5;

    /**
     * Выйти и стоять в деньгах - ветка для режима, под который правила нет.
     * <p>
     * Уверенность <b>минус</b> единица, а не {@link SignalType#POSITION_EXIT} с плюс единицей, и это не
     * придирка. {@code BasicTradeStrategy} читает уверенность и тип не смотрит - так решено осознанно,
     * чтобы закрытие проходило те же пороги, что открытие, а не обходило их. Значит закрывающий сигнал
     * обязан прийти со стороной, которая закрывает: для длинной книги это минус единица. Сигнал с
     * плюс единицей и типом «выход» такая стратегия прочитала бы как покупку.
     */
    public static final SignalSource OUT_OF_MARKET = candles -> new Signal(-1, 1);

    /**
     * Правило по режиму рынка: в восходящем работает трендовая ветка, во флэте - своя, в нисходящем -
     * третья, и обычно это {@link #OUT_OF_MARKET}.
     *
     * <h2>Нисходящая ветка обязательна, и это исправление</h2>
     * Сначала её здесь не было: казалось, что {@link Signal#NEUTRAL} на чтении, под которое ветки не
     * написано, и есть «стоять в деньгах». Это неверно. NEUTRAL не закрывает позицию, а <b>замораживает
     * её</b>: стратегия, уже сидящая в бумаге, получит ноль и останется в ней на всё падение. Парковка
     * требует сигнала, а не молчания.
     * <p>
     * Отдельным параметром, а не зашитым {@link #OUT_OF_MARKET}, потому что книга с шортом захочет туда
     * не выход, а короткую сторону. В этой базе шорт себя не окупает - ставка по займу съедает то, что
     * приносит сторона, - но это измеренное свойство базы, а не свойство конструкции.
     * <p>
     * Отсюда главная оговорка к любому результату такой сборки: <b>парковка и разметка режима
     * смешаны</b>. Улучшение против удержания бумаги даст уже одна парковка, безотносительно того, верно
     * ли размечен режим - в этой базе фонд даёт +10-11% годовых, а бумаги ликвидной трети теряли к нему
     * 7 пунктов годовых. Разделить их можно только рукавом «трендовая ветка одна, без флэтовой».
     *
     * <h2>Ветки должны быть без памяти о позиции</h2>
     * Вторая ошибка той же сборки, и важная для всех, кто будет вешать сюда ветки. Переключатель
     * спрашивает <b>только ту ветку, которой принадлежит чтение</b>, поэтому у ветки, сидящей на
     * состоянии - {@link EntryExitSignalSource}, {@link OnChangeSignalSource}, - в памяти появляются
     * дырки: пока режим флэтовый, трендовая ветка баров не видит. {@link EntryExitSignalSource},
     * открывший позицию перед сменой режима, останется уверен, что держит её, хотя флэтовая ветка её за
     * это время закрыла, и на возврате режима не войдёт заново.
     * <p>
     * Поэтому ветки здесь - состояния, а не события: «длинная, пока цена выше уровня» вместо «вход на
     * пересечении». Событием служит сама смена режима. {@link #trendBranch} с его
     * {@link OnChangeSignalSource} годится как самостоятельное правило, но под этот переключатель его
     * ставить нельзя.
     *
     * <h2>Переключение жёсткое, и это не недосмотр</h2>
     * {@link SmoothSwitchSignalSource} существует потому, что коэффициент, висящий около границы,
     * переворачивает ответ от бара к бару. Здесь висеть около границы нечему: {@link SteadySide} уже
     * сгладил чтение своими двумя порогами, и сглаживать второй раз значило бы растянуть тот же лаг
     * дважды. Цена такого выбора - не дребезг, а запаздывание смены режима, и она измеряется рукавом
     * без гистерезиса, где пороги сведены в один.
     *
     * @param regime   чем размечен режим; ожидается {@link SteadySide} над мерой тренда
     * @param trending правило восходящего режима - состояние, а не событие
     * @param flat     правило флэта; возврату к средней место именно здесь
     * @param falling  правило нисходящего режима; для длинной книги {@link #OUT_OF_MARKET}
     */
    public static SignalSource byRegime(MarketCoefficient regime, SignalSource trending,
                                        SignalSource flat, SignalSource falling) {
        if (regime == null || trending == null || flat == null || falling == null) {
            throw new IllegalArgumentException("Нужны режим и три ветки: тренд, флэт и падение");
        }

        return new RangeSwitchSignalSource(regime, List.of(
            RangeSwitchSignalSource.Branch.from(MIDDLE, trending),
            new RangeSwitchSignalSource.Branch(-MIDDLE, MIDDLE, flat),
            RangeSwitchSignalSource.Branch.below(-MIDDLE, falling)
        ));
    }

    /**
     * @param trend   чем мерить тренд; вход сработает на смене его стороны
     * @param level   уровень выхода - любая формула. Терпимость к нерешительному пробою задаётся здесь же,
     *                через {@link com.siberalt.singularity.strategy.market.TolerantLevel} над средней;
     *                голая средняя означает «выходить при любом переходе через неё»
     * @param ownExit своё правило выхода, или {@link NullSignalSource}, если его нет
     */
    public static SignalSource trendBranch(SignalSource trend, MarketCoefficient level,
                                           SignalSource ownExit) {
        if (trend == null || level == null || ownExit == null) {
            throw new IllegalArgumentException("Нужны мера тренда, уровень выхода и своё правило выхода");
        }

        // Один уровень на всё, и этого достаточно, потому что резкость хода входит в сам уровень - см.
        // TolerantLevel. Выше него держим (кроме фиксации прибыли), ниже выходим; на резком ходу «ниже»
        // начинается у самого уровня, на дрейфе - на зону поддержки глубже.
        MarketCondition above = new PriceAbove(level);
        SignalSource exits = new AnyOfSignalSource(
            new ConditionalExitSignalSource(above.negated()),
            ownExit
        );

        return new EntryExitSignalSource(
            new OnChangeSignalSource(trend),
            // Выше уровня проходит только фиксация прибыли; ниже - любой выход. Через and такое не
            // собрать: там оба условия обязательны, а здесь они подменяют друг друга.
            new FilterSignalSource(exits, new OfType(SignalType.TAKE_PROFIT).or(SignalCondition.of(above.negated())))
        );
    }
}
