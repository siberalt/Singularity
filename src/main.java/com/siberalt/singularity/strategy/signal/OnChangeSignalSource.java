package com.siberalt.singularity.strategy.signal;

import com.siberalt.singularity.entity.candle.Candle;

import java.util.List;

/**
 * Пропускает ответ делегата только на том баре, где сторона сменилась. Событие вместо состояния.
 * <p>
 * Нужно это потому, что меры тренда отвечают <b>состоянием</b>: {@link
 * com.siberalt.singularity.strategy.signal.trend.MovingAverageCrossSignalSource} говорит «быстрая выше
 * медленной» на каждом баре, пока это так. А вход «на кресте» - это <b>событие</b>, и разница между тем и
 * другим измерена дорого.
 * <p>
 * В {@code docs/signals.md} она стоит дважды. Во-первых, вход на кресте даёт +182.9 ± 94 бп на двадцати
 * днях, а случайный день той же восходящей фазы - минус 53.9: то есть находиться в лонге внутри фазы само
 * по себе не даёт ничего, и весь результат принадлежит началу фазы. Во-вторых, расхождение стенда с
 * симулятором на двести пунктов объяснилось ровно этим: стенд входил на переходе, симулятор - всегда, пока
 * сторона положительна, и у одной бумаги от этого зависела сделка на +357%.
 *
 * <h2>Первая увиденная сторона запоминается молча</h2>
 * И это главное решение здесь. На первом баре прогона сторона уже какая-то есть - фаза началась до начала
 * измерения, - и если считать её сменой, то правило войдёт в <b>идущий</b> тренд, то есть сделает именно
 * то, от чего этот источник отличает вход на событии. Поэтому первая сторона только записывается, а
 * сработает лишь следующая смена.
 * <p>
 * Цена этого решения известна: одна фаза на старте окна пропускается всегда. Она же и причина, по которой
 * прогон со скользящим началом обязателен - результат зависит от того, попало ли начало окна внутрь фазы.
 *
 * <h2>Молчание делегата сторону не сбрасывает</h2>
 * Нулевая уверенность - это «сказать нечего», а не «сторона сменилась на никакую». Если считать её сменой,
 * источник, который на прогреве молчит, а потом возвращается к той же стороне, выдаст ложное событие. Так
 * что ноль просто пропускается, а помнится последняя названная сторона.
 */
public class OnChangeSignalSource implements SignalSource {
    private final SignalSource delegate;

    /** Последняя названная делегатом сторона; ноль - он ещё не называл ни одной. */
    private double side;

    public OnChangeSignalSource(SignalSource delegate) {
        if (delegate == null) {
            throw new IllegalArgumentException("Нет источника, у которого ловить смену стороны");
        }

        this.delegate = delegate;
    }

    @Override
    public Signal calculate(List<Candle> lastCandles) {
        Signal reading = delegate.calculate(lastCandles);
        double now = Math.signum(reading.confidence());

        if (now == 0) {
            return Signal.NEUTRAL;
        }

        boolean first = side == 0;
        boolean changed = !first && now != side;

        side = now;

        return changed ? reading : Signal.NEUTRAL;
    }
}
