package com.siberalt.singularity.strategy.signal;

/**
 * О чём сигнал: открыть позицию, закрыть её, или только о направлении рынка.
 * <p>
 * До появления этого перечисления {@link Signal} умел сказать только знак, и «закрыть лонг» было от
 * «встать в шорт» неотличимо. Из-за этого правило выхода под дивидендную отсечку пришлось делать
 * {@link com.siberalt.singularity.strategy.market.MarketCondition} и вешать на
 * {@link SignalSource}-обёртку сроком, а не выражать сигналом - единственным, кто знал сторону открытой
 * позиции, был {@link EntryExitSignalSource}. Тип снимает это ограничение: закрытие можно назвать, не
 * зная, что именно закрывается.
 *
 * <h2>Почему {@link #UNSPECIFIED} - это не заглушка на время миграции</h2>
 * Большинство источников тип знать <b>не может</b>, и это их свойство, а не недоделка. MACD не знает, в
 * позиции вы или нет, - а от этого зависит, вход его сигнал или выход. То же у пересечения средних, у RSI,
 * у наклона EMA. Они имеют мнение о направлении, и только о нём; вход это или выход, решает тот, кто знает
 * состояние счёта. Поэтому {@code UNSPECIFIED} останется навсегда и остаётся значением по умолчанию для
 * сигнала, построенного двухаргументным конструктором.
 *
 * <h2>{@link #TAKE_PROFIT} и {@link #STOP_LOSS} - подвиды выхода</h2>
 * Это важно для потребителя: «это выход?» - вопрос к {@link #closes()}, а не сравнение с одним значением.
 * Сравнение с {@code POSITION_EXIT} молча пропустит стоп, и поймать такую ошибку трудно, потому что стопы
 * срабатывают редко.
 * <p>
 * Сказать, прибылью или убытком кончается выход, может далеко не всякий источник: цены входа он не знает.
 * Поэтому эти два значения - для тех, кто <b>является</b> стопом или целью по построению: трейлинг-стоп,
 * уровень фиксации. Остальным выходам место в {@code POSITION_EXIT}.
 *
 * <h2>Чего тип пока не делает</h2>
 * {@link com.siberalt.singularity.strategy.impl.BasicTradeStrategy} по-прежнему решает по
 * {@link Signal#confidence()} и своим порогам, а тип не читает. Значит типизированный выход, у которого
 * {@code confidence} порога не достигает, сегодня ничего не сделает - словарь появился, а действие по нему
 * ещё нет. До того, как стратегия научится читать тип, закрывающий сигнал обязан вдобавок несть
 * {@code confidence}, переходящий порог продажи, ровно как раньше.
 */
public enum SignalType {
    /** Сказать нечего - {@link Signal#NEUTRAL}. Не «нулевая сила», а «на этом баре мнения нет». */
    NONE,

    /** Есть мнение о направлении, но не о позиции: источник не знает, держите вы что-нибудь или нет. */
    UNSPECIFIED,

    POSITION_ENTRY,

    POSITION_EXIT,

    /** Выход, про который источник знает, что закрывает прибыль - цель, уровень фиксации. */
    TAKE_PROFIT,

    /** Выход, про который источник знает, что закрывает убыток - стоп. */
    STOP_LOSS;

    /** Открывает ли этот сигнал позицию. */
    public boolean opens() {
        return this == POSITION_ENTRY;
    }

    /** Закрывает ли - любым из трёх способов. Спрашивать надо так, а не сравнением с одним значением. */
    public boolean closes() {
        return this == POSITION_EXIT || this == TAKE_PROFIT || this == STOP_LOSS;
    }
}
