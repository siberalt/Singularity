package com.siberalt.singularity.strategy.signal;

/**
 * Что набралось из голосов делегатов, когда несколько источников складывают в один ответ.
 * <p>
 * Вход для {@link TypePolicy} и {@link BalancePolicy}: чем решать, о чём сигнал и какую долю счёта он
 * просит. Передаётся записью, а не списком голосов, по двум причинам. Складывать голоса всё равно
 * приходится проходом, так что список был бы вторым представлением тех же чисел; и {@code calculate}
 * зовут на каждом баре, а в этой базе бары считаются миллионами, так что лишнего списка на бар лучше не
 * заводить.
 *
 * @param confidence     сложенная уверенность - то же число, что уйдёт в {@link Signal#confidence()}
 * @param strength       сложенная величина, в единицах делегатов
 * @param weight         сколько веса вообще проголосовало; ноль означает, что не высказался никто
 * @param positiveWeight вес тех, кто голосовал за покупку
 * @param negativeWeight вес тех, кто голосовал за продажу
 */
public record Votes(double confidence, double strength, double weight,
                    double positiveWeight, double negativeWeight) {
    /**
     * Вес, проголосовавший <b>в сторону ответа</b>.
     * <p>
     * Это не то же, что {@code |confidence|}: сложенная уверенность - разность сторон, а здесь сумма
     * одной из них. При раскладе шестьдесят на сорок уверенность выйдет 0.2, а согласный вес - 0.6, и
     * размер позиции по этим двум числам получается совсем разный. Поэтому величина существует отдельно,
     * а не выводится из уверенности.
     * <p>
     * Ровный раскол даёт ноль: когда ответа нет, согласных с ним тоже нет.
     */
    public double agreeingWeight() {
        if (confidence > 0) {
            return positiveWeight;
        }

        return confidence < 0 ? negativeWeight : 0;
    }

    /** Доля веса, проголосовавшая в сторону ответа, в [0, 1]. */
    public double agreeingShare() {
        return weight == 0 ? 0 : agreeingWeight() / weight;
    }
}
