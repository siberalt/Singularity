package com.siberalt.singularity.strategy.signal;

/**
 * Чем источник, складывающий чужие голоса, решает, какую долю счёта просить.
 * <p>
 * У слияния для этого есть то, чего нет ни у одного делегата: <b>насколько состав согласен</b>. Сегодня
 * эта информация выбрасывается, а размер считается от сложенной уверенности - то есть от <i>разности</i>
 * сторон, где трое против двух дают 0.2, хотя за ответ высказалось шестьдесят процентов веса.
 * <p>
 * Какая из этих двух величин лучше работает размером позиции - вопрос измерения, а не рассуждения, и в
 * этой базе такие вопросы уже решались измерением не раз. Поэтому политика подключается, а по умолчанию
 * стоит {@link #UNDEFINED}: размер по-прежнему выводит
 * {@link com.siberalt.singularity.strategy.impl.quantity.TradeQuantity} из уверенности, и ни один
 * существующий прогон не меняется.
 */
@FunctionalInterface
public interface BalancePolicy {
    double of(Votes votes);

    /**
     * Доли не называть: пусть размер считает тот, кто считает размер. Поведение по умолчанию -
     * {@link Signal#UNDEFINED_BALANCE}.
     */
    BalancePolicy UNDEFINED = votes -> Signal.UNDEFINED_BALANCE;

    /**
     * Доля веса, проголосовавшая в сторону ответа: трое из пяти за - шестьдесят процентов счёта.
     * <p>
     * Ровный раскол даёт ноль, то есть «встать в деньги», и это согласуется с ответом: уверенность при
     * таком раскладе тоже ноль, действовать не на чем.
     */
    BalancePolicy AGREEING_WEIGHT = Votes::agreeingShare;

    /** Та же доля согласного веса, но не больше потолка - когда весь счёт на один инструмент не кладут. */
    static BalancePolicy agreeingWeightUpTo(double cap) {
        if (!(cap > 0) || cap > 1) {
            throw new IllegalArgumentException("Потолок доли лежит в (0, 1], получено " + cap);
        }

        return votes -> votes.agreeingShare() * cap;
    }
}
