package com.siberalt.singularity.strategy.market;

import java.time.Instant;

/**
 * Когда у бумаги ближайшая отсечка - на знании, доступном в заданный момент, а не сегодняшнем.
 * <p>
 * Якорем служит {@code lastBuyDate} - последний день, когда покупка ещё даёт право на дивиденд. Он же и
 * последний день перед гэпом: цена падает на следующий торговый день, то есть в саму отсечку. Поэтому
 * правило «не держать под отсечку» выражается через него, а не через {@code recordDate}, до которого от
 * гэпа ещё два дня расчётов.
 * <p>
 * <b>Инструмент - параметр, а не свойство экземпляра.</b> Календарь на одну бумагу пришлось бы заводить
 * заново на каждую, а правило, которое его спрашивает, видит свечи и знает из них только
 * {@link com.siberalt.singularity.entity.candle.Candle#instrumentId()}. Так что спрашивать надо тем же
 * ключом, которым бумага названа в свечах.
 * <p>
 * <b>Параметр {@code asOf} здесь не для удобства.</b> Календарь, собранный сегодня, знает дивиденды,
 * объявленные позже того бара, на котором его спрашивают, и правило, пользующееся таким знанием, в прогоне
 * выйдет из позиции до того, как о дивиденде стало известно. Отсюда требование: реализация обязана
 * учитывать только то, что было объявлено к {@code asOf}.
 */
public interface DividendCalendar {
    /**
     * Ближайший {@code lastBuyDate} этой бумаги не раньше {@code asOf}, или {@code null}, если такого нет.
     *
     * @param instrumentId бумага в том же виде, в каком она названа в свечах
     * @param asOf         момент, на который известно то, что известно
     */
    Instant nextLastBuyDate(long instrumentId, Instant asOf);

    /** Календарь без дивидендов - для бумаг, которые их не платят, и для прогонов без календаря. */
    DividendCalendar EMPTY = (instrumentId, asOf) -> null;

    /**
     * День, в который попадает момент, - конвенция этого календаря и всех, кто считает расстояние до
     * отсечки.
     * <p>
     * Нужна она потому, что отсечка - это день, а бар - мгновение внутри дня, и смешивать их нельзя.
     * Разница мгновений между баром в десять утра и днём покупки в полночь на день меньше разницы дней, так
     * что окно «два дня до» посчиталось бы тремя. Конвенция стоит здесь, в одном месте, чтобы такой сдвиг
     * нельзя было завести в каждом вызывающем по-своему.
     */
    static long dayOf(Instant at) {
        return Math.floorDiv(at.toEpochMilli(), 24 * 3600_000L);
    }
}
