package com.siberalt.singularity.strategy.market;

import com.siberalt.singularity.entity.candle.Candle;

import java.util.List;

/**
 * Кривая, посчитанная по свечам: число <b>на каждой</b> свече, а не одно число по последним.
 * <p>
 * Это пара к {@link MarketCoefficient}, и разница между ними ровно в этом. Коэффициент отвечает «где
 * сейчас уровень», и для уровня больше ничего не нужно. Но о форме кривой - насколько ход был
 * односторонним, сколько раз средняя изгибалась, какой путь она прошла - по одному числу сказать
 * нечего, а по ряду есть что: см. {@link TrendAngle}.
 * <p>
 * Готовые реализации - это {@code candles -> Sma.seriesOf(candles, period, price)} и такой же ряд по
 * EMA, VWAP или чему угодно ещё; отдельных классов под них не нужно, лямбда и есть вся реализация.
 *
 * <h2>Прогрев - дело самого ряда</h2>
 * Пока у кривой не хватает истории на её же период, в ряду стоит {@link Double#NaN} - так ведут себя
 * {@code Sma.seriesOf} и {@code Ema.seriesOf}, и это часть контракта здесь. Тому, кто ряд читает,
 * сколько именно свечей нужно, знать не обязательно: он видит NaN в своём окне и отвечает NaN сам.
 * Иначе каждый читатель повторял бы у себя арифметику прогрева чужой кривой, и однажды повторил бы её
 * неверно.
 * <p>
 * Длина ряда совпадает с числом свечей: читатели опираются на то, что последнее чтение относится к
 * последней свече.
 */
@FunctionalInterface
public interface MarketSeries {
    double[] of(List<Candle> lastCandles);
}
