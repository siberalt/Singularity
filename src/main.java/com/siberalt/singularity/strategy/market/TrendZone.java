package com.siberalt.singularity.strategy.market;

/**
 * Отрезок истории, на котором режим не менялся: восходящий, нисходящий или флэт.
 * <p>
 * Границы - номера баров в том ряду, по которому зоны считались, обе включительно. Не моменты времени и
 * не индексы свечей: зоны всегда читаются рядом с тем же рядом, а номер бара - единственное, что в нём
 * ищется без поиска.
 * <p>
 * Сторона хранится числом, а не перечислением, потому что её отдаёт {@link MarketCoefficient} - и
 * {@link SteadySide} отдаёт ровно {@code -1}, {@code 0} или {@code 1}. Перечисление пришлось бы заводить
 * вместе с преобразованием туда и обратно, а даёт оно здесь мало: сторон всё равно столько, сколько их
 * различает классификатор.
 * <p>
 * <b>Но число здесь - метка, а не измерение, и {@link #flat()} поэтому сравнивает с нулём точно.</b>
 * Сначала в этом javadoc стояло, что числом сторона хранится ради возможности положить сюда чтение
 * непрерывной меры. Это было неверно и вводило в заблуждение дважды: у непрерывной меры флэт не
 * наступал бы почти никогда - точного нуля у неё не бывает, - а {@link TrendZones} на такой мере вообще
 * не разметил бы историю, выдав по зоне на бар. Поэтому он непрерывное чтение теперь отвергает, и
 * сравнение с нулём корректно по построению.
 * <p>
 * Где непрерывное чтение как раз уместно - это {@code TrendLevelRule.byRegime}: переключатель режима
 * делит его границами, а не равенством, и для него «половина предела» - осмысленный порог.
 */
public record TrendZone(int from, int to, double side) {
    public TrendZone {
        if (from < 0 || to < from) {
            throw new IllegalArgumentException("Зона идёт от бара к бару, получено " + from + ".." + to);
        }

        if (Double.isNaN(side)) {
            throw new IllegalArgumentException("Зона без стороны: о чём она, знать обязательно");
        }
    }

    /** Сколько баров в зоне; обе границы входят. */
    public int bars() {
        return to - from + 1;
    }

    public boolean rising() {
        return side > 0;
    }

    public boolean falling() {
        return side < 0;
    }

    public boolean flat() {
        return side == 0;
    }
}
