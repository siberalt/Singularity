package com.siberalt.singularity.strategy.market;

import com.siberalt.singularity.entity.candle.Candle;

import java.util.ArrayList;
import java.util.List;

/**
 * Разметка истории на зоны режима: соседние бары с одинаковой стороной собираются в отрезки.
 * <p>
 * Чем это отличается от {@link SteadySide}, который и отвечает на вопрос «какой режим сейчас»: тот
 * отвечает про последний бар, а здесь получается вся история разом - где режим начался, где кончился и
 * сколько держался. Для глаз и для отчёта нужно именно это.
 *
 * <h2>Разметка причинная, и заглядывания вперёд здесь нет</h2>
 * Коэффициент спрашивается по барам <b>по порядку</b>, и на баре {@code t} ему показываются только бары
 * до {@code t} включительно. Поэтому зоны - это ровно то, что правило видело в тот момент, а не то, что
 * видно по карте задним числом, и начало зоны всегда <b>позже</b> настоящего изгиба: столько, сколько
 * стоит объявление стороны. Эта задержка - свойство меры, а не разметки, и смотреть на неё надо здесь.
 * <p>
 * Порядок важен ещё по одной причине: {@link SteadySide} держит состояние. Спросить его о середине
 * истории, не пройдя начало, значит получить другой ответ - поэтому проход один и только вперёд.
 *
 * <h2>Окно вместо всей предыстории</h2>
 * Коэффициенту показываются последние {@code window} баров, а не всё начало ряда. Иначе разметка стоила
 * бы квадрата длины - на дневных барах это пустяк, на минутных уже нет, - и ответ от этого не изменился
 * бы: мере нужна её собственная предыстория, а не вся.
 * <p>
 * Окно, меньшее того, что мере нужно, - не ошибка сборки, а молчание: {@link Double#NaN} на каждом баре
 * и ни одной зоны. Проверить это здесь нечем, потому что сколько именно баров нужно чужой кривой, знает
 * только она сама - см. контракт {@link MarketSeries}.
 *
 * <h2>Размечает классификатор, а не измерение</h2>
 * Коэффициент здесь обязан отдавать <b>метку стороны</b> - целое число, как {@link SteadySide} с его
 * {@code -1}, {@code 0} и {@code 1}, - а не непрерывное чтение. Граница зоны определяется равенством
 * меток, и у непрерывной меры равных подряд значений не бывает: {@code TrendAngle}, поданный сюда
 * напрямую, дал бы по зоне на каждый бар, а флэт - состояние «ровно ноль» - не наступил бы никогда.
 * <p>
 * Поэтому дробное чтение отвергается сразу, а не размечается кое-как. Порог, превращающий меру в
 * сторону, должен стоять <b>в одном месте</b> - в самом коэффициенте; второе место, где написано то же
 * самое, рано или поздно разойдётся с первым, и в этой базе это уже измерено на мёртвой зоне.
 * <p>
 * Этим разметка отличается от {@code TrendLevelRule.byRegime}, который непрерывное чтение принимает
 * законно: тот делит его <b>границами диапазонов</b>, а не равенством, и «половина предела» для него
 * осмысленный порог.
 *
 * <h2>Чем заполнены пропуски</h2>
 * Пока мера молчит - прогрев, - баров в зонах нет вовсе: первая зона начинается с первого чтения.
 * Молчание <i>после</i> начала зоны её не закрывает, а продолжает: отсутствие чтения это не смена
 * режима, и объявлять по нему границу значило бы выдумать её.
 */
public final class TrendZones {
    private TrendZones() {
    }

    /**
     * @param bars   ряд, по которому размечается режим
     * @param regime чем размечать; ожидается {@link SteadySide} над мерой тренда
     * @param window сколько последних баров показывать коэффициенту на каждом шаге
     * @return зоны по порядку, без пересечений; вместе они покрывают всё от первого чтения до конца ряда
     */
    public static List<TrendZone> of(List<Candle> bars, MarketCoefficient regime, int window) {
        if (bars == null || regime == null) {
            throw new IllegalArgumentException("Нужны бары и чем размечать режим");
        }

        if (window < 1) {
            throw new IllegalArgumentException("Окно положительно, получено " + window);
        }

        List<TrendZone> zones = new ArrayList<>();
        int from = -1;
        double side = 0;

        for (int at = 0; at < bars.size(); at++) {
            double now = regime.of(bars.subList(Math.max(0, at - window + 1), at + 1));

            if (Double.isNaN(now)) {
                continue;
            }

            if (now != Math.rint(now)) {
                throw new IllegalArgumentException(
                    "Зоны размечает классификатор, а не непрерывная мера: на баре " + at
                        + " получено " + now + ". Порог должен стоять в самом коэффициенте - "
                        + "например в SteadySide, - а не здесь");
            }

            if (from < 0) {
                from = at;
                side = now;
            } else if (now != side) {
                zones.add(new TrendZone(from, at - 1, side));
                from = at;
                side = now;
            }
        }

        if (from >= 0) {
            zones.add(new TrendZone(from, bars.size() - 1, side));
        }

        return zones;
    }
}
