package com.siberalt.singularity.entity.candle;

import java.util.List;

/**
 * Сколько единиц индекса приходится на один бар окна.
 * <p>
 * Нужно везде, где расстояние задано в барах, а свечи адресуются индексом: у сырых свечей индекс - это
 * номер строки, и бар равен единице, а у свёрнутых - нет. Часовой бар несёт индекс минуты, на которой
 * открылся, поэтому соседние часы отличаются примерно на шестьдесят. Мерка, забывшая об этом, тихо
 * перестаёт работать: окрестность в десять баров не группировала ничего, давность касания в тридцать
 * баров читалась как тысяча восемьсот и обнуляла силу всех уровней разом, а срок свежести в двести
 * баров означал двести минут.
 * <p>
 * Шаг усреднён по окну, потому что он неровный: час на краю сессии содержит меньше минут, чем час в
 * середине, а ночь и выходные не содержат их вовсе. Для своей задачи этого достаточно - шаг выбирает
 * окрестность или срок, а не конкретный бар, и ошибка в бар туда или обратно ничего не решает. Точный
 * поиск места каждого экстремума среди баров стоил бы поиска на экстремум, и на плотных окнах это
 * съедало большую часть вызова.
 */
public final class BarSpacing {
    private BarSpacing() {
    }

    /**
     * Средний шаг индексов между соседними барами, не меньше единицы. Окно короче двух баров шага не
     * задаёт, и для него ответ - один: считать иначе не из чего.
     */
    public static double of(List<Candle> candles) {
        if (candles == null || candles.size() < 2) {
            return 1;
        }

        long span = candles.get(candles.size() - 1).getIndex() - candles.get(0).getIndex();

        return Math.max(1, (double) span / (candles.size() - 1));
    }

    /** Тот же шаг целым числом, вниз: им удобно делить индексы на позиции. */
    public static long stepOf(List<Candle> candles) {
        return (long) of(candles);
    }

    /** Столько-то баров окна, выраженные в единицах индекса. */
    public static long unitsOf(List<Candle> candles, long bars) {
        return bars * stepOf(candles);
    }
}
